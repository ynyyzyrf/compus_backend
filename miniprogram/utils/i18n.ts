const DICTS: Record<Locale, Dict> = { 'zh-CN': ZH_CN, 'zh-TW': ZH_TW }

/**
 * Look up a translation by key. Falls back to zh-CN -> raw key.
 *
 *   t('home.hello')              // '歡迎回家'
 *   t('home.hello_name', { name: '張晨' })  // '歡迎回家，張晨'
 */
export function t(key: string, params?: Record<string, string | number>): string {
  const l = locale.get()
  let s = DICTS[l]?.[key]
  if (s === undefined) s = DICTS['zh-CN'][key] ?? key
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      s = s.replace(new RegExp(`\\{\\{${k}\\}\\}`, 'g'), String(v))
    })
  }
  return s
}
